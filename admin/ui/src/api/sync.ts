/* ------------------------------------------------------------------ *
 * 纯函数：表单 → 请求
 * ------------------------------------------------------------------ */

function asString(value: unknown): string {
  if (typeof value === 'string') return value
  if (value === null || value === undefined) return ''
  return String(value)
}

/**
 * 远程 URL 归一：去首尾空白 + 去末尾斜杠。
 *
 * 与后端 `body.remote_url.rstrip("/")` 对齐（前端额外做 trim，旧版也是先 trim 再提交）。
 * 空串保持空串 —— 后端遇到空串**不会清库**，契约 §4.2。
 */
export function normalizeRemoteUrl(raw: unknown): string {
  return asString(raw).trim().replace(/\/+$/, '')
}

/** 是否像 http(s) 绝对地址。仅用于字段提示，不作为保存拦截（后端不校验格式）。 */
export function isHttpUrl(raw: unknown): boolean {
  return /^https?:\/\/\S+$/i.test(normalizeRemoteUrl(raw))
}

/**
 * 生成同步密钥：32 字节 → 64 位十六进制（256 bit）。
 *
 * 后端 `_generate_device_secret()` 是 `secrets.token_hex(32)`，这里保持同等强度；
 * 旧版前端只生成 16 字节（32 hex），属于需要对齐的差异（契约 §七）。
 */
export function generateSyncSecret(byteLength = 32): string {
  const size = Math.min(64, Math.max(1, Math.floor(byteLength)))
  const bytes = new Uint8Array(size)
  const cryptoObj = typeof crypto !== 'undefined' ? crypto : undefined
  if (cryptoObj && typeof cryptoObj.getRandomValues === 'function') {
    cryptoObj.getRandomValues(bytes)
  } else {
    // 兜底：只在极老的浏览器 / 测试环境里走这里，不用于安全用途之外的展示。
    for (let i = 0; i < bytes.length; i += 1) bytes[i] = Math.floor(Math.random() * 256)
  }
  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('')
}

/** 表单 → 请求体：URL 归一、密钥 trim（对齐后端 `.strip()`）。 */
export function normalizeSyncInput(form: SyncFormInput): SyncConfigInput {
  return {
    remote_url: normalizeRemoteUrl(form.remoteUrl),
    secret: asString(form.secret).trim(),
  }
}

/**
 * 表单是否有未保存修改。
 *
 * · URL 按归一后比较（末尾斜杠不算修改）；
 * · 密钥留空提交是"保持现有密钥"，但**清空输入框本身**算修改（保存后会重载出原值）。
 */
export function isSyncFormDirty(form: SyncFormInput, baseline: SyncConfigPayload | null | undefined): boolean {
  if (!baseline) return false
  if (normalizeRemoteUrl(form.remoteUrl) !== normalizeRemoteUrl(baseline.remote_url)) return true
  return asString(form.secret).trim() !== asString(baseline.secret)
}

/* ------------------------------------------------------------------ *
 * 纯函数：响应 → 展示
 * ------------------------------------------------------------------ */

function countPair(value: unknown): SyncCountPair | null {
  if (!value || typeof value !== 'object') return null
  const record = value as Record<string, unknown>
  const added = Number(record.added)
  const updated = Number(record.updated)
  if (!Number.isFinite(added) && !Number.isFinite(updated)) return null
  return {
    added: Number.isFinite(added) ? added : 0,
    updated: Number.isFinite(updated) ? updated : 0,
  }
}

function profileOutcome(value: unknown): SyncProfileOutcome | null {
  if (!value || typeof value !== 'object') return null
  const record = value as Record<string, unknown>
  const applied = record.applied
  const fields = Array.isArray(record.fields) ? record.fields.length : 0
  const errors = Array.isArray(record.errors)
    ? record.errors.map((item) => asString(item)).filter(Boolean)
    : []
  return {
    applied: applied === true ? true : applied === false ? false : null,
    fields,
    errors,
  }
}

/**
 * 本机记录里的 profile 是 SyncProfileOutcome（`fields` 是**个数**），
 * 与线上响应的 `fields: string[]` 形状不同，解析必须分开。
 */
function recordProfile(value: unknown): SyncProfileOutcome | null {
  if (!value || typeof value !== 'object') return null
  const record = value as Record<string, unknown>
  const applied = record.applied
  const fields = Number(record.fields)
  const errors = Array.isArray(record.errors)
    ? record.errors.map((item) => asString(item)).filter(Boolean)
    : []
  if (applied !== true && applied !== false && !Number.isFinite(fields)) return null
  return {
    applied: applied === true ? true : applied === false ? false : null,
    fields: Number.isFinite(fields) ? fields : 0,
    errors,
  }
}

/**
 * `POST /api/sync/push` 响应 → 展示结构。
 *
 * 线上没有回传 `remote_result`（自建接收端、代理改包）时三组计数为 null，界面显示 —，
 * 但推送本身仍算成功（后端返回了 2xx）。
 */
export function summarizePushResult(payload: SyncPushResult | null | undefined): SyncPushSummary {
  const remote = payload && typeof payload === 'object' ? payload : undefined
  const remoteResult = remote?.remote_result
  const summary: SyncPushSummary = {
    remote: asString(remote?.remote),
    accounts: countPair(remoteResult?.accounts),
    models: countPair(remoteResult?.models),
    profile: null,
  }
  const remoteProfile = remoteResult?.client_profile
  if (remoteProfile && typeof remoteProfile === 'object') {
    summary.profile = profileOutcome(remoteProfile)
  } else if (remote?.client_profile === false) {
    // 本地没有可推的客户端参数：线上不会返回 client_profile 结果。
    summary.profile = { applied: null, fields: 0, errors: [] }
  }
  return summary
}

/** 展示文案：账号/模型用 "+新增 / ~更新"，客户端参数按线上应用结果。 */
export function formatPushSummary(summary: SyncPushSummary): SyncPushSummaryText {
  const accounts = summary.accounts
    ? '+' + fmtInt(summary.accounts.added) + ' / ~' + fmtInt(summary.accounts.updated)
    : '—'
  const models = summary.models
    ? '+' + fmtInt(summary.models.added) + ' / ~' + fmtInt(summary.models.updated)
    : '—'
  let profile = '—'
  if (summary.profile) {
    if (summary.profile.applied === true) profile = '已同步 ' + fmtInt(summary.profile.fields) + ' 项'
    else if (summary.profile.applied === false) {
      profile = '未同步：' + (summary.profile.errors.join('；') || '线上未接受')
    } else profile = '为空，未同步'
  }
  return { accounts, models, profile }
}

/** 成功响应 → 本机记录。 */
export function pushRecordFromResult(
  summary: SyncPushSummary,
  at: number = Date.now(),
): SyncPushRecord {
  return {
    at,
    ok: true,
    remote: summary.remote,
    accounts: summary.accounts,
    models: summary.models,
    profile: summary.profile,
    error: '',
  }
}

/** 失败 → 本机记录（保留目标地址与后端 detail，便于用户回看）。 */
export function pushRecordFromError(
  remoteUrl: string,
  message: string,
  at: number = Date.now(),
): SyncPushRecord {
  return {
    at,
    ok: false,
    remote: normalizeRemoteUrl(remoteUrl),
    accounts: null,
    models: null,
    profile: null,
    error: asString(message),
  }
}

/* ------------------------------------------------------------------ *
 * 本机记录读写（localStorage 不可用时静默降级）
 * ------------------------------------------------------------------ */

function defaultStorage(): SyncRecordStorage | null {
  try {
    if (typeof localStorage === 'undefined' || !localStorage) return null
    return localStorage
  } catch {
    return null
  }
}

function parseRecord(raw: string): SyncPushRecord | null {
  try {
    const data = JSON.parse(raw) as unknown
    if (!data || typeof data !== 'object') return null
    const record = data as Record<string, unknown>
    const at = Number(record.at)
    if (!Number.isFinite(at) || at <= 0) return null
    if (typeof record.ok !== 'boolean') return null
    return {
      at,
      ok: record.ok,
      remote: asString(record.remote),
      accounts: countPair(record.accounts),
      models: countPair(record.models),
      profile: recordProfile(record.profile),
      error: asString(record.error),
    }
  } catch {
    return null
  }
}

/** 读最近一次推送记录；没有 / 损坏 / 无存储时返回 null。 */
export function readSyncRecord(storage: SyncRecordStorage | null = defaultStorage()): SyncPushRecord | null {
  if (!storage) return null
  try {
    const raw = storage.getItem(SYNC_RECORD_KEY)
    if (!raw) return null
    return parseRecord(raw)
  } catch {
    return null
  }
}

/** 写最近一次推送记录；写不进去（隐私模式 / 配额）时静默失败。 */
export function writeSyncRecord(
  record: SyncPushRecord,
  storage: SyncRecordStorage | null = defaultStorage(),
): void {
  if (!storage) return
  try {
    storage.setItem(SYNC_RECORD_KEY, JSON.stringify(record))
  } catch {
    /* 写不进去不影响本次会话显示 */
  }
}

export function clearSyncRecord(storage: SyncRecordStorage | null = defaultStorage()): void {
  if (!storage) return
  try {
    storage.removeItem(SYNC_RECORD_KEY)
  } catch {
    /* 忽略 */
  }
}

/* ------------------------------------------------------------------ *
 * 状态行
 * ------------------------------------------------------------------ */

/** GET 响应里的前向兼容字段 → 记录（后端目前不返回，返回 null）。 */
function backendRecord(config: SyncConfigPayload | null | undefined): SyncPushRecord | null {
  if (!config) return null
  const at = toDate(config.last_push_at ?? null)
  if (!at) return null
  const result = config.last_push_result ?? null
  return {
    at: at.getTime(),
    ok: result?.ok === false ? false : true,
    remote: '',
    accounts: countPair(result?.accounts),
    models: countPair(result?.models),
    profile: result?.client_profile && typeof result.client_profile === 'object'
      ? profileOutcome(result.client_profile)
      : null,
    error: asString(config.last_push_error),
  }
}

/**
 * 配置 + 最近推送记录 → 状态行视图。
 *
 * 最近同步优先级：GET 的 `last_push_*`（若后端将来补充）> 本机 `mh.sync.lastPush`。
 * `now` 只影响相对时间，测试时固定它即可稳定断言。
 */
export function describeSyncConfig(
  config: SyncConfigPayload | null | undefined,
  record: SyncPushRecord | null = null,
  now: number = Date.now(),
): SyncStatusView {
  const url = normalizeRemoteUrl(config?.remote_url)
  const secret = asString(config?.secret)
  const masked = asString(config?.secret_masked) || (secret ? maskSecret(secret) : '')
  const fromBackend = backendRecord(config)
  const latest = fromBackend ?? record

  let lastPush: SyncLastPushView | null = null
  if (latest) {
    const text = formatPushSummary({
      remote: latest.remote,
      accounts: latest.accounts,
      models: latest.models,
      profile: latest.profile,
    })
    lastPush = {
      at: latest.at,
      ok: latest.ok,
      resultText: latest.ok ? '成功' : '失败',
      timeText: fmtRelative(latest.at, now),
      timeFull: fmtFullTime(latest.at),
      remoteText: latest.remote ? '推送至 ' + latest.remote : '',
      accountsText: text.accounts,
      modelsText: text.models,
      profileText: text.profile,
      error: latest.error,
      source: fromBackend ? 'backend' : 'local',
    }
  }

  return {
    url: { configured: Boolean(url), value: url },
    secret: {
      configured: Boolean(secret || masked),
      masked,
      autoGenerated: config?.is_auto_generated === true,
    },
    lastPush,
    empty: !url && !secret && !masked,
  }
}
