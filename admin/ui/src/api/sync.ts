/**
 * 线上同步（`/api/sync/*`）：配置线上实例、把本地账号 / 模型配置 / 客户端兼容参数推过去。
 * 契约：docs/ui-v2/contracts/sync.md。
 *
 * 后端：admin/routers/sync.py
 *   · get_config  → GET  /api/sync/config   读配置（库中无密钥时自动生成并落库）
 *   · save_config → POST /api/sync/config   写配置（URL 非空才写、密钥留空沿用）
 *   · push        → POST /api/sync/push     先写库再推送到 {remote_url}/api/sync/receive
 *
 * 字段名与后端完全一致（snake_case 原样保留），不做 camelCase 转换。
 * 页面禁止直接 fetch：请求统一走 ./http。
 */
import { http } from './http'
import { fmtFullTime, fmtInt, fmtRelative, maskSecret, toDate } from '@/utils/format'

/** `POST /api/sync/push` 里线上接收端返回的结构（admin/routers/sync.py:receive）。 */
export interface SyncRemoteCounts {
  added?: number
  updated?: number
}

export interface SyncRemoteProfile {
  applied?: boolean
  source?: string
  fields?: string[]
  errors?: string[]
}

export interface SyncRemoteResult {
  ok?: boolean
  accounts?: SyncRemoteCounts
  models?: SyncRemoteCounts
  client_profile?: SyncRemoteProfile | null
}

/**
 * `GET /api/sync/config` 的响应。
 *
 * `is_auto_generated` 只表示「本次请求刚生成」（get_config 在库中无密钥时生成），
 * 不代表历史上是自动还是自定义 —— 契约 §2.2 已写明，界面不要过度解读。
 *
 * `last_push_*` 是前向兼容的可选字段：当前后端不返回，若将来补充，
 * 状态行优先采用后端值（见 describeSyncConfig）。
 */
export interface SyncConfigPayload {
  remote_url: string
  /** 完整密钥（仅已登录管理员可见，可复制）。 */
  secret: string
  /** 后端打码：`********abcd`（长度 ≤4 时为 `****`，空密钥为空串）。 */
  secret_masked: string
  is_auto_generated: boolean
  last_push_at?: number | string | null
  last_push_result?: SyncRemoteResult | null
  last_push_error?: string | null
}

export interface SyncConfigInput {
  remote_url: string
  secret: string
}

export interface SyncSaveResult {
  ok: boolean
  secret_set: boolean
}

export interface SyncPushResult {
  ok: boolean
  remote: string
  /** 本次推送的本地账号条数（不是线上 upsert 结果）。 */
  accounts: number
  /** 本次推送的本地模型条数。 */
  models: number
  /** 是否带了客户端参数（false = 本地档案为空）。 */
  client_profile: boolean
  profile_fields: string[]
  remote_result?: SyncRemoteResult
}

/** 账号/模型的 upsert 结果。 */
export interface SyncCountPair {
  added: number
  updated: number
}

/** 客户端参数在线上应用的结果；applied=null 表示本地就没有可推的字段。 */
export interface SyncProfileOutcome {
  applied: boolean | null
  fields: number
  errors: string[]
}

/** 推送结果的数据视图（接口响应 → 展示用结构）。 */
export interface SyncPushSummary {
  remote: string
  accounts: SyncCountPair | null
  models: SyncCountPair | null
  profile: SyncProfileOutcome | null
}

/** 三组展示文案；取不到时统一 `—`。 */
export interface SyncPushSummaryText {
  accounts: string
  models: string
  profile: string
}

/** 本机记录的最近一次推送（后端目前没有对应字段，见契约 §2.3）。 */
export interface SyncPushRecord {
  /** 毫秒时间戳。 */
  at: number
  ok: boolean
  /** 推送目标。 */
  remote: string
  accounts: SyncCountPair | null
  models: SyncCountPair | null
  profile: SyncProfileOutcome | null
  error: string
}

export interface SyncStatusView {
  url: { configured: boolean; value: string }
  secret: { configured: boolean; masked: string; autoGenerated: boolean }
  lastPush: SyncLastPushView | null
  /** 连密钥都没有（后端 GET 会自动生成，实际很少出现）。 */
  empty: boolean
}

export interface SyncLastPushView {
  at: number
  ok: boolean
  resultText: string
  timeText: string
  timeFull: string
  remoteText: string
  accountsText: string
  modelsText: string
  profileText: string
  error: string
  /** local = 本机记录；backend = GET 响应里的 last_push_* 字段。 */
  source: 'local' | 'backend'
}

export const SYNC_RECORD_KEY = 'mh.sync.lastPush'

