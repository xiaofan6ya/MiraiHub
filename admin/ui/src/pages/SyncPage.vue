import { useConfirm, useCopy, useRevisit, useToast } from '@/composables'
import { usePlatformStore } from '@/stores/platform'
import { ApiError } from '@/api/http'
import { errorMessage, failureText } from '@/utils/error'
import { useI18n } from '@/i18n'
import {
  describeSyncConfig,
  generateSyncSecret,
  getSyncConfig,
  isSecretMasked,
  isSyncFormDirty,
  needsAdminPassword,
  normalizeRemoteUrl,
  normalizeSyncInput,
  plainSecretOf,
  pushRecordFromError,
  pushRecordFromResult,
  pushToOnline,
  readSyncRecord,
  remoteUrlProblem,
  revealSyncSecret,
  saveSyncConfig,
  summarizePushResult,
  writeSyncRecord,
  type SyncConfigInput,
  type SyncConfigPayload,
  type SyncPushRecord,
} from '@/api/sync'

const { t } = useI18n()
const helpText = computed(() => t('page.sync.help'))
const cardDescription = computed(() => t('page.sync.cardDescription'))
const secretHint = computed(() => t('page.sync.secretHint'))
const sections = computed(() => [
  { id: 'sync-online', title: t('page.sync.section.online') },
  { id: 'sync-status', title: t('page.sync.section.statusCard') },
])

const toast = useToast()
const confirm = useConfirm()
const { copy } = useCopy()
const platform = usePlatformStore()

const config = ref<SyncConfigPayload | null>(null)
/** 最近一次推送：优先展示本机记录（后端 GET 目前没有对应字段）。 */
const record = ref<SyncPushRecord | null>(readSyncRecord())
const form = reactive({ remoteUrl: '', secret: '', adminPassword: '' })
const secretVisible = ref(false)
const firstLoad = ref(true)
const refreshing = ref(false)
const saving = ref(false)
const pushing = ref(false)
const revealing = ref(false)
const loadError = ref<unknown>(null)

/**
 * 掩码模式（新后端只下发掩码，fix_plan S5）：输入框初始为空，留空保存 = 沿用库里的密钥；
 * 「显示 / 复制」要先走 revealSyncSecret()（后端单独接口 + 审计）。旧后端下发明文时为 false，行为不变。
 */
const secretMaskedMode = computed(() => isSecretMasked(config.value) && !form.secret)
const secretPlaceholder = computed(() =>
  secretMaskedMode.value
    ? t('page.sync.placeholder.secretKept', { masked: config.value?.secret_masked || '••••' })
    : t('page.sync.placeholder.secret'),
)

const status = computed(() =>
  config.value ? describeSyncConfig(config.value, record.value, Date.now(), t) : null,
)
const lastPush = computed(() => status.value?.lastPush ?? null)
const statusEmpty = computed(() => status.value?.empty === true)
const configuredUrl = computed(() => (status.value?.url.configured ? status.value.url.value : ''))
const secretMasked = computed(() => status.value?.secret.masked || '')
const secretAutoGenerated = computed(() => status.value?.secret.autoGenerated === true)
const errorText = computed(() => (loadError.value ? errorMessage(loadError.value) : ''))

const busy = computed(() => saving.value || pushing.value)
const dirty = computed(() =>
  config.value
    ? isSyncFormDirty({ remoteUrl: form.remoteUrl, secret: form.secret }, config.value)
    : false,
)
/** 修改已有的同步地址：要输入当前后台登录密码（后端 403 校验）。 */
const needPassword = computed(() =>
  config.value ? needsAdminPassword({ remoteUrl: form.remoteUrl, secret: form.secret }, config.value) : false,
)

const urlHint = computed(() =>
  normalizeRemoteUrl(form.remoteUrl)
    ? t('page.sync.url.hintConfigured')
    : t('page.sync.url.hintEmpty'),
)
const urlError = computed(() => {
  const problem = remoteUrlProblem(form.remoteUrl, config.value?.https_only)
  if (problem === 'invalid') return t('page.sync.url.invalid')
  if (problem === 'httpsOnly') return t('page.sync.url.httpsOnly')
  return ''
})

const saveDisabled = computed(
  () =>
    busy.value ||
    refreshing.value ||
    !config.value ||
    Boolean(urlError.value) ||
    (needPassword.value && !form.adminPassword.trim()),
)

const kvItems = computed<KvItem[]>(() => [
  { label: t('page.sync.kv.url'), slot: 'url' },
  { label: t('page.sync.kv.secret'), slot: 'secret' },
])

function applyForm(payload: SyncConfigPayload): void {
  form.remoteUrl = normalizeRemoteUrl(payload.remote_url)
  // 只回填明文；新后端给的是掩码，回填进去再保存就会把「********abcd」写成新密钥。
  form.secret = plainSecretOf(payload)
  form.adminPassword = ''
}

/**
 * 掩码模式下取明文（显示 / 复制前调用）。成功后把明文记进本地 config 作为基线，
 * 这样回填到输入框不会被当成「未保存修改」。返回空串表示没取到。
 */
async function revealSecret(): Promise<string> {
  const plain = plainSecretOf(config.value)
  if (plain) return plain
  if (!config.value || revealing.value) return ''
  revealing.value = true
  try {
    const payload = await revealSyncSecret()
    const value = String(payload?.secret ?? '')
    if (!value) {
      toast.warning(t('page.sync.toast.noSecret'))
      return ''
    }
    config.value = { ...config.value, secret: value }
    if (!form.secret) form.secret = value
    return value
  } catch (error) {
    if (error instanceof ApiError && error.status === 405) {
      toast.warning(t('page.sync.toast.revealUnsupported'))
    } else if (error instanceof ApiError && error.status === 404) {
      // 新后端：库里还没有密钥时 404（detail 是中文原因）；旧后端没有这个接口也是 404。
      toast.warning(error.message && /[\u4e00-\u9fff]/.test(error.message) ? error.message : t('page.sync.toast.revealUnsupported'))
    } else {
      toast.error(failureText(t('page.sync.action.reveal'), error))
    }
    return ''
  } finally {
    revealing.value = false
  }
}

async function toggleSecretVisible(): Promise<void> {
  if (secretVisible.value) {
    secretVisible.value = false
    return
  }
  if (secretMaskedMode.value) {
    const value = await revealSecret()
    if (!value) return
  }
  secretVisible.value = true
}

function rememberRecord(next: SyncPushRecord): void {
  record.value = next
  writeSyncRecord(next)
}

interface LoadOptions {
  /** 保存/推送成功后强制用响应覆盖表单。 */
  forceForm?: boolean
  /** 后台重取（切平台）失败时只留卡片内 ErrorBlock，不弹 Toast（首次加载失败同样交给 ErrorBlock）。 */
  quiet?: boolean
}

async function load(options: LoadOptions = {}): Promise<void> {
  const isFirst = !config.value
  const hadChanges = dirty.value
  refreshing.value = true
  loadError.value = null
  try {
    const payload = await getSyncConfig()
    config.value = payload
    // 有未保存修改时不要覆盖用户输入（平台切换 / 手动刷新都可能发生）。
    if (options.forceForm || isFirst || !hadChanges) applyForm(payload)
  } catch (error) {
    loadError.value = error
    // 契约 sync.md §六：刷新失败要「保留旧数据 + 卡片内 compact ErrorBlock + Toast」两条都给。
    if (!isFirst && !options.quiet) toast.error(failureText(t('page.sync.action.refresh'), error))
  } finally {
    refreshing.value = false
    firstLoad.value = false
  }
}

function refresh(): void {
  // 用户主动点刷新：失败必须给 Toast（§六「刷新失败」），不能只留卡片内错误块。
  void load()
}

function onUrlBlur(): void {
  form.remoteUrl = normalizeRemoteUrl(form.remoteUrl)
}

async function save(): Promise<void> {
  if (busy.value || !config.value || saveDisabled.value) return
  if (needPassword.value && !form.adminPassword.trim()) {
    toast.warning(t('page.sync.toast.passwordRequired'))
    return
  }
  saving.value = true
  try {
    const body: SyncConfigInput = normalizeSyncInput({ remoteUrl: form.remoteUrl, secret: form.secret })
    if (needPassword.value) body.admin_password = form.adminPassword
    await saveSyncConfig(body)
    toast.success(t('page.sync.toast.saved'))
    secretVisible.value = false
    // 以库里的实际值为准：空 URL 不写库、空密钥沿用旧值，都只有重取才准确。
    await load({ forceForm: true })
  } catch (error) {
    if (error instanceof ApiError && error.status === 403) {
      form.adminPassword = ''
      toast.error(t('page.sync.toast.passwordWrong'))
    } else {
      toast.error(failureText(t('page.sync.action.save'), error))
    }
  } finally {
    saving.value = false
  }
}

function discard(): void {
  if (!config.value) return
  const hadChanges = dirty.value
  applyForm(config.value)
  secretVisible.value = false
  if (hadChanges) toast.info(t('page.sync.toast.reset'))
}

async function regenerate(): Promise<void> {
  const confirmed = await confirm({
    title: t('page.sync.confirm.regenerate.title'),
    message: t('page.sync.confirm.regenerate.body'),
    okText: t('page.sync.confirm.regenerate.ok'),
  })
  if (!confirmed) return
  form.secret = generateSyncSecret()
  secretVisible.value = true
  toast.success(t('page.sync.toast.regenerated'))
}

async function copySecret(): Promise<void> {
  const value = form.secret || plainSecretOf(config.value) || (secretMaskedMode.value ? await revealSecret() : '')
  if (!value) {
    toast.warning(t('page.sync.toast.noSecret'))
    return
  }
  const ok = await copy(value)
  if (ok) toast.success(t('common.copied'))
  else toast.error(t('common.copyFailed'))
}

async function push(): Promise<void> {
  if (busy.value) return
  // 后端只推往已保存的地址；输入框和已保存的不一致时先保存（否则 400）。
  if (dirty.value) {
    toast.warning(t('page.sync.toast.saveFirst'))
    return
  }
  const url = configuredUrl.value
  if (!url) {
    toast.warning(t('page.sync.toast.needUrl'))
    return
  }
  const confirmed = await confirm({
    title: t('page.sync.confirm.push.title'),
    message: t('page.sync.confirm.push.body'),
    okText: t('page.sync.confirm.push.ok'),
  })
  if (!confirmed) return
  pushing.value = true
  try {
    const payload = await pushToOnline()
    rememberRecord(pushRecordFromResult(summarizePushResult(payload)))
    toast.success(t('page.sync.toast.pushed'))
    await load({ forceForm: true })
  } catch (error) {
    rememberRecord(pushRecordFromError(url, errorMessage(error)))
    toast.error(failureText(t('page.sync.action.push'), error))
  } finally {
    pushing.value = false
  }
}

let stopPlatformWatch: (() => void) | null = null

// 二次进入（KeepAlive 命中）：保留旧数据、不出骨架，后台静默刷新（11-polish-motion §2）。
// 设置型页面：有未保存修改时不刷新，免得覆盖草稿。
useRevisit(
  () => {
    if (!dirty.value && !saving.value) void load({ quiet: true })
  },
  { minIntervalMs: 10_000 },
)

onMounted(() => {
  void load()
  // 旧版切平台会重跑 loadSyncConfig()（console-app.js:3349），这里保持同样行为。
  stopPlatformWatch = platform.onChange(() => {
    void load({ quiet: true })
  })
})

onBeforeUnmount(() => {
  stopPlatformWatch?.()
  stopPlatformWatch = null
})
</script>

