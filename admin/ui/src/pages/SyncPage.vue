<script setup lang="ts">
/**
 * S07 同步设置 /sync（模板 C，设计稿 06-pages-d P19；10-visual-refresh §1.6 重做）
 *
 * 契约：docs/ui-v2/contracts/sync.md
 * 后端：admin/routers/sync.py（get_config / reveal / save_config / push）
 *
 * 布局：两张卡 ——「线上实例」（左标签右控件：地址 / 密钥 / 需要时的后台密码）与
 * 「同步状态」（只读状态 + 页面唯一主按钮「同步到线上」）。保存统一走底部保存条。
 *
 * 2026-11-24 后端安全改动（fixlog_security §6 前端 1～3）：
 *   · GET 的 secret 只给掩码：输入框不回填掩码；显示 / 复制走 POST /api/sync/config/reveal；
 *   · 修改**已有**同步地址要带 admin_password（当前后台登录密码），错了 403；
 *   · push 只推往已保存的地址：有未保存修改时先拦下提示「先保存」，请求不再带地址；
 *   · 推送结果里 accounts.skipped_not_newer = 线上更新、未覆盖的账号数，显示在结果里。
 * 接口数据是全局 system_settings，与平台无关；但旧版切平台会重跑 loadSyncConfig()
 * （console-app.js:3349 / platform-context.md §6.1），这里保持同样行为。
 */
import { computed, onBeforeUnmount, onMounted, reactive, ref } from 'vue'
import { NInput, NSkeleton } from 'naive-ui'
import { CloudUpload, Copy, Eye, EyeOff, RefreshCw } from 'lucide-vue-next'
import SettingsLayout from '@/layout/SettingsLayout.vue'
