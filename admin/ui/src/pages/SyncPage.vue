<script setup lang="ts">
/**
 * S07 同步设置 /sync（模板 C，设计稿 06-pages-d P19）
 *
 * 契约：docs/ui-v2/contracts/sync.md
 * 后端：admin/routers/sync.py（get_config / save_config / push）
 *
 * 本页只做三件事：读配置、保存配置、把本地数据推到线上；推送结果与只读状态行按契约 §2 展示。
 * 接口数据是全局 system_settings，与平台无关；但旧版切平台会重跑 loadSyncConfig()
 * （console-app.js:3349 / platform-context.md §6.1），这里保持同样行为。
 */
import { computed, onBeforeUnmount, onMounted, reactive, ref } from 'vue'
import { NInput, NSkeleton } from 'naive-ui'
import { CloudUpload, Copy, Eye, EyeOff, RefreshCw } from 'lucide-vue-next'
import SettingsLayout from '@/layout/SettingsLayout.vue'
import SettingsCard from '@/layout/SettingsCard.vue'
import { Badge, Btn, Copyable, Empty, ErrorBlock, FormField, IconBtn, KV, Section } from '@/components'
import type { KvItem } from '@/components'
import { useConfirm, useCopy, useToast } from '@/composables'
import { usePlatformStore } from '@/stores/platform'
import { errorMessage, failureText } from '@/utils/error'
import {
  describeSyncConfig,
  generateSyncSecret,
  getSyncConfig,
  isHttpUrl,
  isSyncFormDirty,
  normalizeRemoteUrl,
  normalizeSyncInput,
  pushRecordFromError,
  pushRecordFromResult,
  pushToOnline,
  readSyncRecord,
  saveSyncConfig,
  summarizePushResult,
  writeSyncRecord,
  type SyncConfigPayload,
  type SyncPushRecord,
} from '@/api/sync'

const HELP_TEXT =
  '本地数据视为最新。配置线上实例的 URL 与密钥（HMAC 签名）后，点「同步到线上」把本地账号、模型配置与客户端兼容参数（UA / 版本号 / 请求头）推送过去。' +
  '线上实例需配置相同密钥，并通过 /api/sync/receive 接收。版本与产品字段从本机安装包读取，OS 与硬件字段按本机系统实测（只在装了客户端的机器上有效）；' +
  '线上服务器探测不到客户端，一律以同步过来的档案为准。'

const CARD_DESCRIPTION =
  '推送会用本机账号、模型配置与客户端兼容参数覆盖线上实例的同名数据；保存只改本机的 URL 与密钥。'

const SECRET_HINT =
  '与线上实例一致。留空提交表示保持现有密钥；保存后会重新显示库里的密钥。'

const SECTIONS = [{ id: 'sync-online', title: '线上同步' }]

const toast = useToast()
const confirm = useConfirm()
const { copy } = useCopy()
const platform = usePlatformStore()

const config = ref<SyncConfigPayload | null>(null)
/** 最近一次推送：优先展示本机记录（后端 GET 目前没有对应字段）。 */
const record = ref<SyncPushRecord | null>(readSyncRecord())
const form = reactive({ remoteUrl: '', secret: '' })
const secretVisible = ref(false)
const firstLoad = ref(true)
const refreshing = ref(false)
const saving = ref(false)
const pushing = ref(false)
const loadError = ref<unknown>(null)

const status = computed(() =>
  config.value ? describeSyncConfig(config.value, record.value) : null,
)
const lastPush = computed(() => status.value?.lastPush ?? null)
const statusEmpty = computed(() => status.value?.empty === true)
const configuredUrl = computed(() => (status.value?.url.configured ? status.value.url.value : ''))
const secretMasked = computed(() => status.value?.secret.masked || '')
const secretAutoGenerated = computed(() => status.value?.secret.autoGenerated === true)
const errorText = computed(() => (loadError.value ? errorMessage(loadError.value) : ''))

const busy = computed(() => saving.value || pushing.value)
const saveDisabled = computed(() => !dirty.value || busy.value || refreshing.value || !config.value)
const dirty = computed(() =>
  config.value
    ? isSyncFormDirty({ remoteUrl: form.remoteUrl, secret: form.secret }, config.value)
    : false,
)

const urlHint = computed(() =>
  normalizeRemoteUrl(form.remoteUrl)
    ? '线上实例地址，末尾的 / 会自动去掉。'
    : '留空不会写入后端：已配置的地址无法通过保存清除。',
)
const urlError = computed(() => {
  const value = normalizeRemoteUrl(form.remoteUrl)
  return value && !isHttpUrl(value) ? '不是 http(s) 地址；后端不校验格式，但推送一定失败。' : ''
})

const kvItems = computed<KvItem[]>(() => [
  { label: '远程 URL', slot: 'url', block: true },
  { label: '密钥', slot: 'secret' },
])

function applyForm(payload: SyncConfigPayload): void {
  form.remoteUrl = normalizeRemoteUrl(payload.remote_url)
  form.secret = String(payload.secret ?? '')
}

function rememberRecord(next: SyncPushRecord): void {
  record.value = next
  writeSyncRecord(next)
}

interface LoadOptions {
  /** 保存/推送成功后强制用响应覆盖表单。 */
  forceForm?: boolean
  /** 刷新失败时是否弹 Toast（首次加载失败交给 ErrorBlock）。 */
  silent?: boolean
}

async function load(options: LoadOptions = {}): Promise<void> {
  const isFirst = !config.value
  const hadChanges = dirty.value
  refreshing.value = true
  loadError.value = null
  try {
    const payload = await getSyncConfig()
    config.value = payload
    // 有未保存修改时不要覆盖用户输入（平台切换 / 手动刷新都可能发生）。
    if (options.forceForm || isFirst || !hadChanges) applyForm(payload)
  } catch (error) {
    loadError.value = error
    if (!isFirst && !options.silent) toast.error(failureText('刷新同步配置', error))
  } finally {
    refreshing.value = false
    firstLoad.value = false
  }
}

function refresh(): void {
  void load({ silent: true })
}

function onUrlBlur(): void {
  form.remoteUrl = normalizeRemoteUrl(form.remoteUrl)
}

async function save(): Promise<void> {
  if (busy.value || !config.value) return
  saving.value = true
  try {
    await saveSyncConfig(normalizeSyncInput({ remoteUrl: form.remoteUrl, secret: form.secret }))
    toast.success('已保存同步配置')
    // 以库里的实际值为准：空 URL 不写库、空密钥沿用旧值，都只有重取才准确。
    await load({ forceForm: true })
  } catch (error) {
    toast.error(failureText('保存配置', error))
  } finally {
    saving.value = false
  }
}

function reset(): void {
  if (!config.value) return
  const hadChanges = dirty.value
  applyForm(config.value)
  if (hadChanges) toast.info('已恢复为上次保存的配置')
}

async function regenerate(): Promise<void> {
  const confirmed = await confirm({
    title: '重新生成同步密钥？',
    message: '生成后需要把新密钥同步到线上实例，否则线上会以「签名校验失败」拒绝接收。',
    okText: '重新生成',
  })
  if (!confirmed) return
  form.secret = generateSyncSecret()
  secretVisible.value = true
  toast.success('已生成新密钥，记得点「保存配置」')
}

async function copySecret(): Promise<void> {
  const value = form.secret || config.value?.secret || ''
  if (!value) {
    toast.warning('还没有可复制的密钥')
    return
  }
  const ok = await copy(value)
  if (ok) toast.success('已复制')
  else toast.error('复制失败：浏览器拒绝了剪贴板访问，请手动选中复制')
}

async function push(): Promise<void> {
  if (busy.value) return
  const url = normalizeRemoteUrl(form.remoteUrl)
  if (!url) {
    toast.warning('请先填写远程 URL')
    return
  }
  const confirmed = await confirm({
    title: '同步到线上？',
    message: '会用本地账号、模型配置与客户端参数覆盖线上实例的同名数据。推送前会把输入框里的 URL 与密钥先写入本机库。',
    okText: '同步到线上',
  })
  if (!confirmed) return
  pushing.value = true
  try {
    const payload = await pushToOnline(normalizeSyncInput({ remoteUrl: url, secret: form.secret }))
    rememberRecord(pushRecordFromResult(summarizePushResult(payload)))
    toast.success('已同步到线上')
    await load({ forceForm: true })
  } catch (error) {
    rememberRecord(pushRecordFromError(url, errorMessage(error)))
    toast.error(failureText('同步到线上', error))
  } finally {
    pushing.value = false
  }
}

let stopPlatformWatch: (() => void) | null = null

onMounted(() => {
  void load()
  // 旧版切平台会重跑 loadSyncConfig()（console-app.js:3349），这里保持同样行为。
  stopPlatformWatch = platform.onChange(() => {
    void load({ silent: true })
  })
})

onBeforeUnmount(() => {
  stopPlatformWatch?.()
  stopPlatformWatch = null
})
</script>

<template>
  <SettingsLayout title="同步设置" :help="HELP_TEXT" :sections="SECTIONS" :dirty="dirty">
    <template #actions>
      <Btn variant="default" :icon="RefreshCw" :loading="refreshing" @click="refresh">刷新</Btn>
    </template>

    <SettingsCard
      id="sync-online"
      title="线上同步"
      :description="CARD_DESCRIPTION"
      :dirty="dirty"
      :loading="saving || refreshing"
      save-label="保存配置"
      :save-disabled="saveDisabled"
      @save="save"
      @reset="reset"
    >
      <template #actions>
        <Btn
          variant="default"
          :icon="CloudUpload"
          :loading="pushing"
          :disabled="firstLoad || refreshing || saving"
          @click="push"
        >
          同步到线上
        </Btn>
      </template>

      <!-- 首次加载：骨架 -->
      <div v-if="firstLoad" class="sync-skeleton" aria-busy="true">
        <NSkeleton height="32px" :sharp="false" />
        <NSkeleton height="32px" :sharp="false" />
        <NSkeleton height="20px" width="65%" :sharp="false" text />
      </div>

      <!-- 首次加载失败：整块错误 + 重试 -->
      <ErrorBlock
        v-else-if="loadError && !config"
        title="同步配置加载失败"
        :detail="errorText"
        @retry="load()"
      />

      <template v-else>
        <ErrorBlock
          v-if="loadError"
          compact
          title="刷新同步配置失败，当前显示上次加载的值"
          :detail="errorText"
          @retry="load()"
        />

        <Section title="连接" first>
          <div class="form-grid">
            <FormField label="远程 URL" :hint="urlHint" :error="urlError">
              <NInput
                v-model:value="form.remoteUrl"
                placeholder="https://online.example.com"
                :disabled="busy"
                @blur="onUrlBlur"
              />
            </FormField>

            <FormField label="同步密钥（HMAC 签名用）" :hint="SECRET_HINT">
              <div class="secret-row">
                <NInput
                  v-model:value="form.secret"
                  class="secret-input"
                  :type="secretVisible ? 'text' : 'password'"
                  placeholder="与线上实例一致的密钥"
                  autocomplete="off"
                  :disabled="busy"
                >
                  <template #suffix>
                    <IconBtn
                      :label="secretVisible ? '隐藏密钥' : '显示密钥'"
                      :icon="secretVisible ? EyeOff : Eye"
                      @click="secretVisible = !secretVisible"
                    />
                    <IconBtn label="复制密钥" :icon="Copy" @click="copySecret" />
                  </template>
                </NInput>
                <Btn variant="quiet" :disabled="busy" @click="regenerate">重新生成</Btn>
              </div>
            </FormField>
          </div>
        </Section>

        <Section title="同步内容">
          <p class="hint">
            账号（平台、UID、名称、企业、域名、状态、登录态、额度）· 模型配置（平台、模型 ID、倍率、备注）·
            客户端兼容参数（UA、版本号、风控头与指纹）。
          </p>
          <p class="hint">
            线上实例需配置相同密钥，通过 <code class="mono">/api/sync/receive</code> 校验签名后接收。
          </p>
        </Section>

        <Section title="当前状态">
          <Empty
            v-if="statusEmpty"
            description="还没有配置线上实例。填写远程 URL 并保存后即可同步。"
          />

          <template v-else>
            <KV :items="kvItems">
              <template #url>
                <Copyable v-if="configuredUrl" :value="configuredUrl" />
                <span v-else class="muted">未配置</span>
              </template>
              <template #secret>
                <span class="secret-line">
                  <span class="mono">{{ secretMasked || '未设置' }}</span>
                  <Badge v-if="secretAutoGenerated" tone="brand">本次访问自动生成</Badge>
                </span>
              </template>
            </KV>

            <div class="last-push">
              <div class="last-push__head">
                <span class="last-push__label">最近同步</span>
                <template v-if="lastPush">
                  <Badge :tone="lastPush.ok ? 'ok' : 'danger'">{{ lastPush.resultText }}</Badge>
                  <span class="last-push__time" :title="lastPush.timeFull">{{ lastPush.timeText }}</span>
                  <span v-if="lastPush.remoteText" class="last-push__remote mono">
                    {{ lastPush.remoteText }}
                  </span>
                </template>
                <span v-else class="last-push__none">尚未同步</span>
              </div>

              <p v-if="lastPush" class="last-push__detail">
                账号 <span class="tnum">{{ lastPush.accountsText }}</span> ·
                模型 <span class="tnum">{{ lastPush.modelsText }}</span> ·
                客户端参数 {{ lastPush.profileText }}
              </p>
              <p v-if="lastPush?.error" class="last-push__error">{{ lastPush.error }}</p>
            </div>
          </template>
        </Section>
      </template>
    </SettingsCard>
  </SettingsLayout>
</template>

